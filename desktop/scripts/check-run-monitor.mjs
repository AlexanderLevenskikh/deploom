import fs from 'node:fs'

const monitor = fs.readFileSync('src/data/processMonitor.ts', 'utf8')
const view = fs.readFileSync('src/components/RunMonitor.tsx', 'utf8')
const logPanel = fs.readFileSync('src/components/LogPanel.tsx', 'utf8')
const hook = fs.readFileSync('src/hooks/useDependencyFlow.ts', 'utf8')
const main = fs.readFileSync('electron/main.ts', 'utf8')

const requireText = (source, pattern, message) => {
  if (!pattern.test(source)) throw new Error(message)
}

requireText(hook, /startedAt:\s*number/, 'active logical run must persist startedAt')
requireText(hook, /activeRunStartedAt:\s*selectedActiveRun\?\.startedAt/, 'hook must expose active run start')
requireText(monitor, /runStartedAt !== undefined[\s\S]*entry\.receivedAt >= runStartedAt/, 'monitor must scope by logical run, not only child job id')
requireText(monitor, /runElapsedSeconds/, 'monitor must expose total logical run elapsed time')
requireText(monitor, /attemptElapsedSeconds/, 'monitor must expose current attempt elapsed time')
requireText(monitor, /Baseline solve-and-verify \\w\+ started;.*maxIterations/, 'monitor must parse Baseline iteration budget')
requireText(monitor, /Baseline verify \\w\+ iteration \(\\d\+\):.*assignment=/, 'monitor must parse exact-assignment iterations')
requireText(monitor, /graph certification \\w\+ \\d\+\\\/\\d\+/, 'monitor must recognize graph certification')
requireText(monitor, /blocked exact failing assignment/, 'monitor must recognize confirmed exact conflicts')
requireText(view, /if \(state\.dependency\)[\s\S]*else if \(state\.retry\)/, 'live work progress must take precedence over retry counter')
requireText(view, /monitor\.totalTime/, 'monitor must render total time')
requireText(view, /monitor\.attemptTime/, 'monitor must render current attempt time')
requireText(main, /BASELINE_CONSTRAINT_BUDGET_EXHAUSTED/, 'legacy deterministic Baseline budget exhaustion must remain non-retryable')
requireText(main, /BASELINE_VERIFICATION_PLATEAU/, 'semantic Baseline plateau must be non-retryable')
requireText(main, /BASELINE_VERIFICATION_HARD_BUDGET_EXHAUSTED/, 'hard Baseline safety exhaustion must be non-retryable')
requireText(main, /BASELINE_SOLVER_REPEATED_FAILED_ASSIGNMENT/, 'repeated confirmed failing assignment must be non-retryable')
requireText(main, /EXACT_SOLVER_PROOF_REQUIRED/, 'unfinished exact solver proof must be non-retryable')
requireText(main, /FIXED_INPUT_CONSTRAINT_CONFLICT/, 'fixed-input proof conflict must be non-retryable')
requireText(monitor, /DEPLOOM_PROGRESS_V2 /, 'monitor must consume structured Baseline progress')
requireText(monitor, /prefixIndex = trimmed\.indexOf\(STRUCTURED_BASELINE_PREFIX\)/, 'structured telemetry must tolerate transport prefixes')
requireText(monitor, /minimizing-conflict/, 'monitor must expose Block F conflict minimization')
requireText(monitor, /projectCheck: undefined,[\s\S]*currentOperation: message/, 'minimization must clear stale graph-certification project progress')
requireText(monitor, /const currentCheck = structuredNumber\(structured, 'check'\)/, 'monitor must parse live minimization check number')
requireText(monitor, /maxChecks: structuredNumber\(structured, 'maxChecks'\)/, 'monitor must parse live minimization check budget')
requireText(monitor, /proof: structuredNumber\(structured, 'proof'\)/, 'monitor must parse live minimization proof number')
requireText(monitor, /proofs: structuredNumber\(structured, 'proofs'\)/, 'monitor must parse live minimization proof count')
requireText(view, /monitor\.minimizationProgress/, 'RunMonitor must prioritize minimization progress over stale project checks')
requireText(view, /monitor\.currentCandidateSize/, 'RunMonitor must render current minimized candidate size')
requireText(view, /monitor\.minimizationProof/, 'RunMonitor must render fresh proof progress')
requireText(view, /monitor\.minimization/, 'RunMonitor must render conflict minimization')
requireText(monitor, /allowedIterations/, 'monitor must expose the live adaptive iteration budget')
requireText(monitor, /learnedConstraints/, 'monitor must expose learned-constraint progress')
requireText(monitor, /entry\.stream !== 'system' && action !== 'baseline'/, 'Baseline process stdout/stderr must feed deterministic monitor parsing')
if (!monitor.includes('/\\[dependency (\\d+)\\/(\\d+)\\]')) throw new Error('monitor must parse dependency scan progress')
requireText(monitor, /fieldNumber\(line, 'fixedInputs'\)/, 'monitor must parse Block H fixed-input peer-solver telemetry')
requireText(monitor, /solverManagedInputs/, 'monitor must expose Block H solver-managed input count')
requireText(view, /monitor\.solverManagedInputs/, 'RunMonitor must render solver-managed input count')
requireText(view, /monitor\.fixedInputs/, 'RunMonitor must render fixed resolver input count')
requireText(view, /state\.conflict\.boundedSlice \? 'true' : 'false'/, 'boundedSlice must render without untyped common.yes/common.no keys')
requireText(logPanel, /DEPLOOM_PROGRESS_V2 /, 'machine Baseline telemetry must be filtered from user-facing logs')
if (/common\.yes|common\.no/.test(view)) throw new Error('RunMonitor must not use nonexistent common.yes/common.no translation keys')
const structuredIndex = monitor.indexOf('const structured = structuredBaselineProgress(line)')
const systemGateIndex = monitor.indexOf("if (entry.stream !== 'system' && action !== 'baseline') continue")
if (structuredIndex < 0 || systemGateIndex < 0 || structuredIndex > systemGateIndex) {
  throw new Error('structured Baseline telemetry must be parsed before the Baseline-aware prose gate')
}
if (!/entry\.line\.includes\('DEPLOOM_PROGRESS_V2 '\)/.test(logPanel)) {
  throw new Error('machine telemetry filter must tolerate transport prefixes')
}

console.log('Run monitor logical-run / retry / elapsed-time contracts OK')
